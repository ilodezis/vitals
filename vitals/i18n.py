def format_date_human(d: object, lang: str | None = None) -> str:
    """Format a date as human words without year ('30 сентября' in ru, 'September 30' in en)."""
    import datetime as _dt

    if isinstance(d, str):
        try:
            d = _dt.date.fromisoformat(d[:10])
        except ValueError:
            return d
    if not isinstance(d, (_dt.date, _dt.datetime)):
        return str(d)
    active_lang = lang or current_lang.get()
    if active_lang == "ru":
        return f"{d.day} {_RU_MONTHS_GEN[d.month - 1]}"
    return f"{_EN_MONTHS_LONG[d.month - 1]} {d.day}"
